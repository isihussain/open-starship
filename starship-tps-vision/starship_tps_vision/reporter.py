"""
Inspection reporting and maintenance work order generation.
"""

from pathlib import Path
import json
from typing import Dict, Any

from .detector import InspectionBatchResult


class InspectionReporter:
    """
    Exports TPS inspection findings to structured JSON and Markdown work orders.
    """

    @staticmethod
    def export_json(batch_result: InspectionBatchResult, file_path: str, indent: int = 2) -> None:
        p = Path(file_path)
        p.parent.mkdir(parents=True, exist_ok=True)
        with open(p, "w", encoding="utf-8") as f:
            json.dump(batch_result.to_dict(), f, indent=indent)

    @staticmethod
    def generate_markdown_report(batch_result: InspectionBatchResult, file_path: str) -> str:
        """
        Creates a clean Markdown work order for ground maintenance crews.
        """
        p = Path(file_path)
        p.parent.mkdir(parents=True, exist_ok=True)

        lines = [
            "# Starship TPS Tile Inspection and Maintenance Work Order",
            "",
            "## Summary Statistics",
            f"- **Total Tiles Inspected:** {batch_result.total_inspected}",
            f"- **Intact Tiles:** {batch_result.intact_count}",
            f"- **Defective Tiles:** {batch_result.defective_count}",
            f"- **Critical Immediate Replacements:** {batch_result.critical_replacements_required}",
            "",
            "### Defect Breakdown",
            f"- Missing / Detached Tiles: {batch_result.missing_count}",
            f"- Structurally Cracked Tiles: {batch_result.cracked_count}",
            f"- Chipped Edges / Corners: {batch_result.chipped_count}",
            f"- Inter-Tile Gap Expansions (Plasma Leak Risk): {batch_result.gap_expansion_count}",
            "",
            "## Prioritized Maintenance Queue (Critical & High Priority)",
            "",
            "| Rank | Tile ID | Structural Zone | Axial Z | Azimuth | Defect Type | Priority Score | Action Required |",
            "|---|---|---|---|---|---|---|---|",
        ]

        # Filter only defective tiles, top priority first:
        defective_tiles = [r for r in batch_result.results if r.severity_level in ("CRITICAL", "HIGH", "MEDIUM")]

        if not defective_tiles:
            lines.append("| - | None | - | - | - | No Defects Detected | 0.0 | Flight Ready |")
        else:
            for idx, tile in enumerate(defective_tiles[:30], 1):
                lines.append(
                    f"| {idx} | `{tile.tile_id}` | {tile.zone_id} | {tile.z_hull_m:.2f}m | "
                    f"{tile.azimuth_deg:.1f}° | **{tile.detected_defect.value}** | "
                    f"`{tile.priority_score:.1f}` ({tile.severity_level}) | `{tile.action_required}` |"
                )

        lines.extend([
            "",
            "---",
            "This work order is generated by fusing flight aerothermal load telemetry with ground optical inspection data.",
        ])

        content = "\n".join(lines)
        with open(p, "w", encoding="utf-8") as f:
            f.write(content)

        return content
