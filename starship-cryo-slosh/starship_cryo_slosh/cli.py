"""
Command line interface for starship-cryo-slosh.
"""

import argparse
import json
import sys
from pathlib import Path

from .tank import HeaderTankAssembly
from .simulator import SloshSimulator


def main():
    parser = argparse.ArgumentParser(
        description="Simulate cryogenic propellant slosh and ullage gas ingestion from flight telemetry."
    )
    parser.add_argument(
        "--telemetry",
        type=str,
        required=True,
        help="Path to input flight telemetry JSON file (generated by starship-flip-gnc).",
    )
    parser.add_argument(
        "--with-baffles",
        action="store_true",
        help="Enable internal annular anti-slosh damping baffles in header tanks.",
    )
    parser.add_argument(
        "--export-json",
        type=str,
        default="",
        help="Path to export coupled slosh telemetry JSON file.",
    )

    args = parser.parse_args()

    telem_path = Path(args.telemetry)
    if not telem_path.exists():
        print(f"Error: Telemetry file not found at {args.telemetry}", file=sys.stderr)
        sys.exit(1)

    with open(telem_path, "r", encoding="utf-8") as f:
        telemetry_data = json.load(f)

    assembly = HeaderTankAssembly.default_starship(with_baffles=args.with_baffles)
    simulator = SloshSimulator(assembly=assembly)

    print(f"Analyzing {len(telemetry_data)} telemetry records (Baffles: {'ON' if args.with_baffles else 'OFF'})...")
    result, history = simulator.simulate_telemetry(telemetry_data)

    print(f"\n--- Slosh Analysis Report ---")
    print(f"Risk Level: {result.risk_level}")
    print(f"LOX Gas Ingestion: {'YES' if result.lox_gas_ingestion_detected else 'NO'} "
          f"({result.lox_total_gas_exposure_time_s} s, Min Depth: {result.lox_min_submergence_m} m)")
    print(f"CH4 Gas Ingestion: {'YES' if result.ch4_gas_ingestion_detected else 'NO'} "
          f"({result.ch4_total_gas_exposure_time_s} s, Min Depth: {result.ch4_min_submergence_m} m)")
    print(f"Peak Disturbance Torque: {result.max_slosh_torque_nm} N*m")
    print(f"Peak Lateral CoM Shift: {result.max_com_shift_x_mm} mm")
    print(f"Summary: {result.summary_message}")

    if args.export_json:
        out_p = Path(args.export_json)
        out_p.parent.mkdir(parents=True, exist_ok=True)
        with open(out_p, "w", encoding="utf-8") as f:
            json.dump([pt.to_dict() for pt in history], f, indent=2)
        print(f"\nExported {len(history)} slosh points to {args.export_json}")

    sys.exit(0 if result.risk_level != "CRITICAL_CAVITATION" else 2)


if __name__ == "__main__":
    main()
